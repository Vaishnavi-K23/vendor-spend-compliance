"""Score the hand review: precision per rule with 95% Wilson intervals.

Reads validation/review_workbook.xlsx (filled in by the reviewer) and writes
validation/results.md. Rows marked `unclear` are reported but excluded from
precision; blank verdicts are counted as not yet reviewed.

Usage: python -m src.validation.score_review
"""
import sys

import pandas as pd
from statsmodels.stats.proportion import proportion_confint

from src.validation.build_review import SAMPLES, VALIDATION_DIR, WORKBOOK

RESULTS = VALIDATION_DIR / "results.md"

# For the two unflagged samples a "true_issue" is a MISS, so the metric is the miss rate.
UNFLAGGED = {"missed_duplicates", "missed_after_end"}


def score(sheet: str, df: pd.DataFrame) -> dict:
    v = df["verdict"].fillna("").str.strip().str.lower()
    reviewed = v[v != ""]
    true, false, unclear = (reviewed == "true_issue").sum(), (reviewed == "false_positive").sum(), (reviewed == "unclear").sum()
    decided = true + false
    rate = true / decided if decided else None
    lo, hi = proportion_confint(true, decided, method="wilson") if decided else (None, None)
    reasons = df.loc[v != "", "reason"].fillna("(none)").str.strip().replace("", "(none)").value_counts()
    return {"sheet": sheet, "sample": len(df), "reviewed": len(reviewed), "true": true, "false": false,
            "unclear": unclear, "rate": rate, "lo": lo, "hi": hi,
            "metric": "miss rate" if sheet in UNFLAGGED else "precision", "reasons": reasons}


def fmt(x):
    return "–" if x is None else f"{x:.0%}"


def main() -> None:
    sheets = pd.read_excel(WORKBOOK, sheet_name=list(SAMPLES), dtype=str)
    rows = [score(name, df) for name, df in sheets.items()]

    lines = ["# Phase 4 validation results", "",
             "Generated by `python -m src.validation.score_review` from `validation/review_workbook.xlsx`.",
             "Precision = true issues ÷ (true issues + false positives); `unclear` rows are excluded. "
             "For the unflagged samples the same ratio is a miss rate. Intervals are 95% Wilson.", "",
             "| Sample | Metric | Reviewed | True | False | Unclear | Rate | 95% CI |",
             "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        lines.append(f"| {r['sheet']} | {r['metric']} | {r['reviewed']}/{r['sample']} | {r['true']} | {r['false']} "
                     f"| {r['unclear']} | {fmt(r['rate'])} | {fmt(r['lo'])}–{fmt(r['hi'])} |")
    lines += ["", "## Reasons", ""]
    for r in rows:
        if r["reviewed"]:
            lines.append(f"**{r['sheet']}:** " + ", ".join(f"{k} ({n})" for k, n in r["reasons"].items()))
            lines.append("")
    RESULTS.write_text("\n".join(lines), encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to cp1252
    print("\n".join(lines))


if __name__ == "__main__":
    main()
