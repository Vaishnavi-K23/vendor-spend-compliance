"""Score the hand review: precision per rule with 95% Wilson intervals.

Reads validation/review_workbook.xlsx and writes validation/results.md. Rows
marked `unclear` are reported but excluded from precision; blank verdicts are
counted as not yet reviewed.

Two extra views:
  - dollar-weighted precision where a sheet carries amounts
  - "current rules": the same reviewed rows, keeping only those the rules in the
    database still flag, so a rule change can be judged on the original sample.

Usage: python -m src.validation.score_review
"""
import sys

import pandas as pd
from statsmodels.stats.proportion import proportion_confint

from src.db import connect
from src.validation.build_review import SAMPLES, VALIDATION_DIR, WORKBOOK

RESULTS = VALIDATION_DIR / "results.md"

# For the two unflagged samples a "true_issue" is a MISS, so the metric is the miss rate.
UNFLAGGED = {"missed_duplicates", "missed_after_end"}
AMOUNT_COLUMNS = {"off_contract": "amount", "off_contract_top_payees": "off_contract_amount_2022_plus",
                  "duplicates": "amount", "over_award": "over_award_amount_2025_plus"}

# Which reviewed rows the current rules still flag (key column, SQL returning flagged keys).
STILL_FLAGGED = {
    "duplicates": ("payment_id", "select payment_id::text from dw.mart_payment_exceptions where is_possible_duplicate"),
    "paid_after_end": ("payment_id", "select payment_id::text from dw.mart_payment_exceptions where is_paid_after_end"),
    "over_award": ("contract_number", "select contract_number from dw.mart_contract_spend where over_award_amount_2025_plus > 0"),
    "off_contract": ("payment_id", "select payment_id::text from dw.mart_payment_exceptions where exception_type = 'off_contract'"),
    "off_contract_top_payees": ("payee", """select distinct v.vendor_name from dw.mart_payment_exceptions e
                                          join dw.dim_vendor v using (vendor_key) where e.exception_type = 'off_contract'"""),
}


def verdicts(df: pd.DataFrame) -> pd.Series:
    return df["verdict"].fillna("").str.strip().str.lower()


def rate(true: int, false: int):
    decided = true + false
    if not decided:
        return None, None, None
    lo, hi = proportion_confint(true, decided, method="wilson")
    return true / decided, lo, hi


def score(sheet: str, df: pd.DataFrame) -> dict:
    v = verdicts(df)
    reviewed = v[v != ""]
    true, false, unclear = (reviewed == "true_issue").sum(), (reviewed == "false_positive").sum(), (reviewed == "unclear").sum()
    r, lo, hi = rate(true, false)
    usd = None
    if sheet in AMOUNT_COLUMNS:
        amt = pd.to_numeric(df[AMOUNT_COLUMNS[sheet]], errors="coerce").fillna(0)
        t_usd, f_usd = amt[v == "true_issue"].sum(), amt[v == "false_positive"].sum()
        usd = t_usd / (t_usd + f_usd) if t_usd + f_usd else None
    reasons = df.loc[v != "", "reason"].fillna("(none)").str.strip().replace("", "(none)").value_counts()
    return {"sheet": sheet, "sample": len(df), "reviewed": len(reviewed), "true": true, "false": false,
            "unclear": unclear, "rate": r, "lo": lo, "hi": hi, "usd_rate": usd,
            "metric": "miss rate" if sheet in UNFLAGGED else "precision", "reasons": reasons}


def current_rules(sheets: dict[str, pd.DataFrame]) -> list[dict]:
    out = []
    with connect() as conn:
        for sheet, (key, sql) in STILL_FLAGGED.items():
            flagged = {row[0] for row in conn.execute(sql).fetchall()}
            df = sheets[sheet]
            kept = df[df[key].astype(str).str.replace(r"\.0$", "", regex=True).isin(flagged)]
            v = verdicts(kept)
            true, false, unclear = (v == "true_issue").sum(), (v == "false_positive").sum(), (v == "unclear").sum()
            r, lo, hi = rate(true, false)
            out.append({"sheet": sheet, "kept": len(kept), "sample": len(df), "true": true,
                        "false": false, "unclear": unclear, "rate": r, "lo": lo, "hi": hi})
    return out


def fmt(x):
    return "–" if x is None else f"{x:.0%}"


def main() -> None:
    sheets = pd.read_excel(WORKBOOK, sheet_name=list(SAMPLES), dtype=str)
    rows = [score(name, df) for name, df in sheets.items()]
    reviewers = sorted({r for df in sheets.values() if "reviewer" in df for r in df["reviewer"].dropna().unique()})

    lines = ["# Phase 4 validation results", "",
             "Generated by `python -m src.validation.score_review` from `validation/review_workbook.xlsx`.",
             f"Reviewer(s): {', '.join(reviewers) or '(not recorded)'}.", "",
             "Precision = true issues ÷ (true issues + false positives); `unclear` rows are excluded. "
             "For the unflagged samples the same ratio is a miss rate. Intervals are 95% Wilson.", "",
             "## As sampled (rules at sampling time)", "",
             "| Sample | Metric | Reviewed | True | False | Unclear | Rate | 95% CI | $-weighted |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        lines.append(f"| {r['sheet']} | {r['metric']} | {r['reviewed']}/{r['sample']} | {r['true']} | {r['false']} "
                     f"| {r['unclear']} | {fmt(r['rate'])} | {fmt(r['lo'])}–{fmt(r['hi'])} | {fmt(r['usd_rate'])} |")

    lines += ["", "## Current rules (same reviewed rows, kept only if still flagged)", "",
              "| Sample | Still flagged | True | False | Unclear | Precision | 95% CI |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
    for r in current_rules(sheets):
        lines.append(f"| {r['sheet']} | {r['kept']}/{r['sample']} | {r['true']} | {r['false']} | {r['unclear']} "
                     f"| {fmt(r['rate'])} | {fmt(r['lo'])}–{fmt(r['hi'])} |")

    lines += ["", "## Reasons", ""]
    for r in rows:
        if r["reviewed"]:
            lines.append(f"**{r['sheet']}:** " + ", ".join(f"{k} ({n})" for k, n in r["reasons"].items()))
            lines.append("")
    RESULTS.write_text("\n".join(lines), encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to cp1252
    print("\n".join(lines))


if __name__ == "__main__":
    main()
